def week_range(start):
    """그날부터 7일 범위 문자열. 예: '10/5 ~ 10/11'. 화면의 주 표기는 모두 이 꼴로 맞춘다."""
    import numpy as np
    import pandas as pd
    s = pd.Timestamp(start)
    e = pd.Timestamp(np.datetime64(s.to_datetime64(), "D") + np.timedelta64(6, "D"))
    return f"{s.month}/{s.day} ~ {e.month}/{e.day}"

