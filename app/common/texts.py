def week_range(start):
    """발행일부터 7일 범위 문자열. 예: '10/8(목) ~ 10/14(수)'"""
    import numpy as np
    import pandas as pd
    s = pd.Timestamp(start)
    e = pd.Timestamp(np.datetime64(s.to_datetime64(), "D") + np.timedelta64(6, "D"))
    d = "월화수목금토일"
    return f"{s.month}/{s.day}({d[s.weekday()]}) ~ {e.month}/{e.day}({d[e.weekday()]})"
